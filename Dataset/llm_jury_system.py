"""
LLM Jury System for Metrics Code Generation & Validation
==========================================================
- 1 LLM writes code for unknown metrics
- 3-5 LLMs validate the code
- User gets to see and approve before execution
"""

import google.generativeai as genai
import os
import ast
import json
from typing import List, Dict, Tuple, Optional
from dataclasses import dataclass
from enum import Enum


class ValidationResult(Enum):
    APPROVED = "approved"
    REJECTED = "rejected"
    NEEDS_REVISION = "needs_revision"


@dataclass
class JuryVote:
    """Individual jury member's vote"""
    judge_id: str
    result: ValidationResult
    reasoning: str
    score: float  # 0-100
    suggested_fixes: List[str] = None


@dataclass
class CodeProposal:
    """Code generated by the generator LLM"""
    metric_name: str
    description: str
    code: str
    dependencies: List[str]
    expected_output_type: str
    reasoning: str


class LLMJurySystem:
    """
    Intelligent Jury System for Code Validation
    """
    
    def __init__(self, api_key: str = None):
        self.api_key = api_key or os.getenv('GOOGLE_API_KEY')
        if self.api_key:
            genai.configure(api_key=self.api_key)
        
        # Different models/temperatures for diversity
        self.generator_config = {
            'temperature': 0.7,
            'top_p': 0.95,
        }
        
        self.jury_configs = [
            {'temperature': 0.3, 'top_p': 0.9},  # Conservative judge
            {'temperature': 0.5, 'top_p': 0.95}, # Balanced judge
            {'temperature': 0.7, 'top_p': 0.9},  # Creative judge
            {'temperature': 0.4, 'top_p': 0.85}, # Strict judge
            {'temperature': 0.6, 'top_p': 0.92}, # Moderate judge
        ]
    
    def generate_metric_code(
        self,
        metric_description: str,
        available_metrics: Dict[str, any],
        context: str = ""
    ) -> CodeProposal:
        """
        Generator LLM creates code for unknown metric
        """
        
        prompt = f"""You are an expert Python developer creating metrics extraction code for git repositories.

**Task:** Generate Python code to calculate the following metric:
**Metric Description:** {metric_description}

**Context:** {context}

**Available Base Metrics:** 
{json.dumps(list(available_metrics.keys()), indent=2)}

**Requirements:**
1. Write a complete Python function that calculates this metric
2. Function name should be: calculate_custom_metric()
3. Function should accept: repo_path (Path object) and base_metrics (dict)
4. Return a single numeric value or a dict with multiple values
5. Use only standard libraries or: git, pandas, numpy, pathlib
6. Include error handling
7. Add docstring explaining the calculation

**Output Format (JSON):**
{{
    "metric_name": "suggested_name_for_metric",
    "description": "clear description of what this measures",
    "code": "complete Python code here",
    "dependencies": ["list", "of", "imports"],
    "expected_output_type": "float|int|dict",
    "reasoning": "why this implementation is correct"
}}

Generate the code now:"""

        try:
            model = genai.GenerativeModel(
                'gemini-2.0-flash-exp',
                generation_config=self.generator_config
            )
            
            response = model.generate_content(prompt)
            response_text = response.text.strip()
            
            # Extract JSON from markdown if present
            if '```json' in response_text:
                response_text = response_text.split('```json')[1].split('```')[0].strip()
            elif '```' in response_text:
                response_text = response_text.split('```')[1].split('```')[0].strip()
            
            result = json.loads(response_text)
            
            return CodeProposal(
                metric_name=result['metric_name'],
                description=result['description'],
                code=result['code'],
                dependencies=result['dependencies'],
                expected_output_type=result['expected_output_type'],
                reasoning=result['reasoning']
            )
            
        except Exception as e:
            print(f"❌ Code generation error: {e}")
            return None
    
    def validate_code_with_jury(
        self,
        proposal: CodeProposal,
        num_judges: int = 3
    ) -> Tuple[bool, List[JuryVote], str]:
        """
        Multiple LLM judges validate the proposed code
        """
        
        votes: List[JuryVote] = []
        
        validation_prompt = f"""You are an expert code reviewer validating Python code for metrics calculation.

**Proposed Metric:**
Name: {proposal.metric_name}
Description: {proposal.description}
Expected Output: {proposal.expected_output_type}

**Generated Code:**
```python
{proposal.code}
```

**Generator's Reasoning:**
{proposal.reasoning}

**Your Task:** Evaluate this code on:
1. **Correctness:** Does it correctly implement the described metric?
2. **Security:** Is it safe to execute? No malicious code?
3. **Efficiency:** Is the implementation reasonably efficient?
4. **Code Quality:** Is it well-structured and maintainable?
5. **Error Handling:** Does it handle edge cases?

**Output Format (JSON):**
{{
    "result": "approved|rejected|needs_revision",
    "score": 85,
    "reasoning": "detailed explanation of your decision",
    "issues_found": ["list of issues if any"],
    "suggested_fixes": ["list of suggestions if needs_revision"]
}}

Provide your evaluation:"""

        for i in range(min(num_judges, len(self.jury_configs))):
            try:
                model = genai.GenerativeModel(
                    'gemini-2.0-flash-exp',
                    generation_config=self.jury_configs[i]
                )
                
                response = model.generate_content(validation_prompt)
                response_text = response.text.strip()
                
                # Extract JSON
                if '```json' in response_text:
                    response_text = response_text.split('```json')[1].split('```')[0].strip()
                elif '```' in response_text:
                    response_text = response_text.split('```')[1].split('```')[0].strip()
                
                result = json.loads(response_text)
                
                vote = JuryVote(
                    judge_id=f"Judge_{i+1}",
                    result=ValidationResult(result['result']),
                    reasoning=result['reasoning'],
                    score=result['score'],
                    suggested_fixes=result.get('suggested_fixes', [])
                )
                
                votes.append(vote)
                
            except Exception as e:
                print(f"⚠️ Judge {i+1} error: {e}")
                continue
        
        # Calculate consensus
        approved = sum(1 for v in votes if v.result == ValidationResult.APPROVED)
        rejected = sum(1 for v in votes if v.result == ValidationResult.REJECTED)
        needs_revision = sum(1 for v in votes if v.result == ValidationResult.NEEDS_REVISION)
        
        avg_score = sum(v.score for v in votes) / len(votes) if votes else 0
        
        # Decision logic
        if approved > len(votes) / 2:
            decision = True
            summary = f"✅ APPROVED by {approved}/{len(votes)} judges (Avg Score: {avg_score:.1f})"
        elif rejected > len(votes) / 2:
            decision = False
            summary = f"❌ REJECTED by {rejected}/{len(votes)} judges (Avg Score: {avg_score:.1f})"
        else:
            decision = False
            summary = f"⚠️ NEEDS REVISION - Mixed votes (Avg Score: {avg_score:.1f})"
        
        return decision, votes, summary
    
    def revise_code_based_on_feedback(
        self,
        original_proposal: CodeProposal,
        jury_votes: List[JuryVote]
    ) -> CodeProposal:
        """
        Generator LLM revises code based on jury feedback
        """
        
        feedback_summary = "\n".join([
            f"Judge {v.judge_id}: {v.reasoning}\nSuggestions: {', '.join(v.suggested_fixes or [])}"
            for v in jury_votes
        ])
        
        revision_prompt = f"""You are revising your previously generated code based on expert feedback.

**Original Metric:**
Name: {original_proposal.metric_name}
Description: {original_proposal.description}

**Your Original Code:**
```python
{original_proposal.code}
```

**Jury Feedback:**
{feedback_summary}

**Task:** Revise the code addressing all the concerns raised by the judges.

**Output Format (JSON):**
{{
    "metric_name": "same or updated name",
    "description": "same or updated description",
    "code": "revised Python code",
    "dependencies": ["updated list"],
    "expected_output_type": "float|int|dict",
    "reasoning": "what you changed and why"
}}

Generate revised code:"""

        try:
            model = genai.GenerativeModel(
                'gemini-2.0-flash-exp',
                generation_config=self.generator_config
            )
            
            response = model.generate_content(revision_prompt)
            response_text = response.text.strip()
            
            if '```json' in response_text:
                response_text = response_text.split('```json')[1].split('```')[0].strip()
            elif '```' in response_text:
                response_text = response_text.split('```')[1].split('```')[0].strip()
            
            result = json.loads(response_text)
            
            return CodeProposal(
                metric_name=result['metric_name'],
                description=result['description'],
                code=result['code'],
                dependencies=result['dependencies'],
                expected_output_type=result['expected_output_type'],
                reasoning=result['reasoning']
            )
            
        except Exception as e:
            print(f"❌ Revision error: {e}")
            return None
    
    def full_jury_process(
        self,
        metric_description: str,
        available_metrics: Dict[str, any],
        num_judges: int = 3,
        max_revisions: int = 2
    ) -> Tuple[Optional[CodeProposal], List[JuryVote], str]:
        """
        Complete process: Generate → Validate → Revise if needed
        """
        
        print(f"\n{'='*60}")
        print(f"🏛️ LLM JURY PROCESS STARTING")
        print(f"{'='*60}")
        print(f"📝 Metric: {metric_description}")
        print(f"👨‍⚖️ Judges: {num_judges}")
        
        # Step 1: Generate initial code
        print(f"\n🤖 Generator LLM creating code...")
        proposal = self.generate_metric_code(metric_description, available_metrics)
        
        if not proposal:
            return None, [], "Failed to generate code"
        
        print(f"✅ Code generated for: {proposal.metric_name}")
        
        # Step 2: Jury validation (with revision loop)
        revision_count = 0
        all_votes = []
        
        while revision_count <= max_revisions:
            print(f"\n⚖️ Jury Deliberation (Round {revision_count + 1})...")
            
            approved, votes, summary = self.validate_code_with_jury(proposal, num_judges)
            all_votes.extend(votes)
            
            print(f"\n{summary}")
            
            if approved:
                print(f"✅ Code APPROVED by jury!")
                return proposal, votes, summary
            
            # Check if we should revise
            needs_revision_count = sum(1 for v in votes if v.result == ValidationResult.NEEDS_REVISION)
            
            if needs_revision_count > 0 and revision_count < max_revisions:
                print(f"\n🔄 Revising code based on feedback...")
                proposal = self.revise_code_based_on_feedback(proposal, votes)
                revision_count += 1
            else:
                print(f"\n❌ Code could not be approved after {revision_count + 1} rounds")
                return None, votes, summary
        
        return None, all_votes, "Max revisions reached"


# Test function
def test_jury_system():
    """Test the LLM jury system"""
    
    jury = LLMJurySystem()
    
    # Example: Unknown metric
    metric_description = """
    Calculate the 'Developer Experience Score' which combines:
    - Average time between commits (lower is better for activity)
    - Bug fix ratio (lower is better)
    - Code complexity per LOC (lower is better)
    
    Formula: 100 - (normalized_avg_commit_gap * 40 + bug_fix_ratio * 30 + complexity_density * 30)
    """
    
    available_metrics = {
        'total_commits': 150,
        'project_age_days': 365,
        'bug_fix_ratio': 0.15,
        'estimated_complexity': 450,
        'total_loc': 5000,
    }
    
    proposal, votes, summary = jury.full_jury_process(
        metric_description,
        available_metrics,
        num_judges=3
    )
    
    if proposal:
        print(f"\n{'='*60}")
        print(f"🎉 FINAL APPROVED CODE")
        print(f"{'='*60}")
        print(f"\nMetric Name: {proposal.metric_name}")
        print(f"Description: {proposal.description}")
        print(f"\nCode:\n{proposal.code}")
        print(f"\nReasoning: {proposal.reasoning}")
    else:
        print(f"\n{'='*60}")
        print(f"❌ CODE NOT APPROVED")
        print(f"{'='*60}")
        print(f"Summary: {summary}")


if __name__ == "__main__":
    test_jury_system()
